import { createHash } from 'node:crypto';
import { AppError } from '../lib/domain';
import { validatedMetadata } from '../lib/nft-metadata';
import { verifyCreatorMetadata } from './erc721-creator-mint';
import { fetchMediaWithFallback } from './media';

export type Go721ArtworkSource = {
  title: string; description: string; image: string; externalUrl: string; metadataUri: string;
};

/**
 * GO#|O source-of-truth check for a revised ARTWORK draft.
 * A new pinned JSON CID is sufficient; a creator-mint intent is NOT required
 * (and must not be created for this reserved 3+27 collection).
 *
 * The immutable, content-addressed bytes must exactly represent the displayed
 * draft fields. The canonical pin endpoint serializes these same fields.
 */
export async function verifyGo721ArtworkSource(
  draft: Go721ArtworkSource,
  fetcher: (uri: string, limit: number) => Promise<Buffer> = fetchMediaWithFallback,
) {
  if (!/^ipfs:\/\/bafkrei[a-z2-7]{52}$/.test(draft.metadataUri))
    throw new AppError('GO721_METADATA_REQUIRED',
      'Pin the finalized JSON metadata before saving this artwork revision.', 409);
  const bytes = await fetcher(draft.metadataUri, 24576);
  const verified = verifyCreatorMetadata(draft.metadataUri, bytes);
  const metadata = verified.metadata;
  if (metadata.name !== draft.title || metadata.description !== draft.description ||
      metadata.image !== draft.image ||
      (metadata.external_url ?? '') !== draft.externalUrl ||
      metadata.attributes.length !== 0)
    throw new AppError('GO721_METADATA_MISMATCH',
      'The pinned JSON does not match the saved title, description, image, or external URL. Pin the edited JSON first.', 409);
  // Identical field order and JSON bytes to the server-controlled pin endpoint:
  // no alternate serialization can silently slip into the final 3+27 bundle.
  const canonical = Buffer.from(validatedMetadata(metadata).bytes);
  if (!bytes.equals(canonical))
    throw new AppError('GO721_METADATA_FORMAT',
      'The pinned JSON bytes differ from the canonical metadata generated by the artwork editor.', 409);
  return { json: canonical, sha256: createHash('sha256').update(canonical).digest('hex') };
}
